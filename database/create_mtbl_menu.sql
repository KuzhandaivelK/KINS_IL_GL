-- Create MTBL_MENU table in KINS schema
CREATE TABLE KINS.MTBL_MENU (
    MENU_ID         VARCHAR2(50)    NOT NULL,
    MENU_NAME       VARCHAR2(100)   NOT NULL,
    MENU_PARENT_ID  VARCHAR2(50),
    MENU_SEQ_NO     NUMBER(4, 0)    DEFAULT 1 NOT NULL,
    MENU_PATH       VARCHAR2(200),
    MENU_ICON       VARCHAR2(50)    DEFAULT 'Layers',
    IS_ACTIVE       VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
    CREATED_BY      VARCHAR2(50)    DEFAULT 'admin',
    CREATED_AT      DATE            DEFAULT SYSDATE,
    MODIFIED_BY     VARCHAR2(50),
    MODIFIED_AT     DATE,
    CONSTRAINT PK_MTBL_MENU PRIMARY KEY (MENU_ID),
    CONSTRAINT FK_MTBL_MENU_PARENT FOREIGN KEY (MENU_PARENT_ID) 
        REFERENCES KINS.MTBL_MENU (MENU_ID) ON DELETE SET NULL,
    CONSTRAINT CHK_MTBL_MENU_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

-- Comments on table and columns
COMMENT ON TABLE KINS.MTBL_MENU IS 'Dynamic application menu table for database-driven navigation';
COMMENT ON COLUMN KINS.MTBL_MENU.MENU_ID IS 'Unique identifier for the menu item';
COMMENT ON COLUMN KINS.MTBL_MENU.MENU_NAME IS 'Display label of the menu';
COMMENT ON COLUMN KINS.MTBL_MENU.MENU_PARENT_ID IS 'Parent menu identifier for nested hierarchy';
COMMENT ON COLUMN KINS.MTBL_MENU.MENU_SEQ_NO IS 'Display sorting order sequence';
COMMENT ON COLUMN KINS.MTBL_MENU.MENU_PATH IS 'Frontend route URL';
COMMENT ON COLUMN KINS.MTBL_MENU.MENU_ICON IS 'Lucide icon identifier';
COMMENT ON COLUMN KINS.MTBL_MENU.IS_ACTIVE IS 'Active status flag (Y=Active, N=Inactive)';

