-- 2. Create MTBL_IL_MEDICAL_GRID (Age Band x Sum Assured Band Master Grid)
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_tables WHERE table_name = 'MTBL_IL_MEDICAL_GRID';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE MTBL_IL_MEDICAL_GRID (
        GRID_ID                     NUMBER(10,0)      NOT NULL,
        AGE_FROM                    NUMBER(3,0)       NOT NULL,
        AGE_TO                      NUMBER(3,0)       NOT NULL,
        SA_FROM                     NUMBER(17,2)      NOT NULL,
        SA_TO                       NUMBER(17,2)      NOT NULL,
        MEDICAL_CODE                VARCHAR2(30)      NOT NULL,
        MEDICAL_CATEGORY            VARCHAR2(100)     NOT NULL,
        REQUIRED_TESTS              VARCHAR2(500)     NOT NULL,
        IS_MEDICAL_REQUIRED         CHAR(1)           DEFAULT ''Y'' NOT NULL,
        IS_ACTIVE                   CHAR(1)           DEFAULT ''Y'' NOT NULL,
        CREATED_BY                  VARCHAR2(50)      DEFAULT ''ADMIN'' NOT NULL,
        CREATED_ON                  DATE              DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_MTBL_IL_MED_GRID PRIMARY KEY (GRID_ID),
        CONSTRAINT CHK_IL_MG_REQ CHECK (IS_MEDICAL_REQUIRED IN (''Y'', ''N'')),
        CONSTRAINT CHK_IL_MG_ACT CHECK (IS_ACTIVE IN (''Y'', ''N''))
      )
    ';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_IL_MED_GRID_BANDS ON MTBL_IL_MEDICAL_GRID (AGE_FROM, AGE_TO, SA_FROM, SA_TO)';
  END IF;
END;
/

-- 3. Create T_PROPOSAL_MEDICAL_DOC (Proposal Medical Examination Documents)
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_tables WHERE table_name = 'T_PROPOSAL_MEDICAL_DOC';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE T_PROPOSAL_MEDICAL_DOC (
        MED_DOC_ID                  NUMBER(10,0)      NOT NULL,
        PROP_NO                     VARCHAR2(30)      NOT NULL,
        TEST_NAME                   VARCHAR2(150)     NOT NULL,
        FILE_NAME                   VARCHAR2(255)     NOT NULL,
        STORED_FILE_NAME            VARCHAR2(255)     NOT NULL,
        FILE_PATH                   VARCHAR2(500)     NOT NULL,
        MIME_TYPE                   VARCHAR2(100),
        FILE_SIZE                   NUMBER(12,0)      DEFAULT 0,
        EXAM_DATE                   DATE,
        CLINIC_NAME                 VARCHAR2(150),
        REMARKS                     VARCHAR2(500),
        IS_ACTIVE                   CHAR(1)           DEFAULT ''Y'' NOT NULL,
        UPLOADED_BY                 VARCHAR2(50)      DEFAULT ''ADMIN'' NOT NULL,
        UPLOADED_ON                 DATE              DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_T_PROP_MED_DOC PRIMARY KEY (MED_DOC_ID),
        CONSTRAINT CHK_PROP_MDOC_ACT CHECK (IS_ACTIVE IN (''Y'', ''N''))
      )
    ';
    EXECUTE IMMEDIATE 'CREATE INDEX IDX_PROP_MED_DOC_NO ON T_PROPOSAL_MEDICAL_DOC (PROP_NO)';
  END IF;
END;
