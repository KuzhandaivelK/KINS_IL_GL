-- 5. Seed Individual Life Medical Document Storage Path in STBL_SYS_PARAM
MERGE INTO STBL_SYS_PARAM t
USING (
  SELECT
    'IL_MED_DOC_PATH' AS SYS_PARAM_CODE,
    'MED_UPLOAD' AS SYS_SUB_PARAM,
    'D:\KINSUREPLUS\KINS\UPLOADS\IL_MEDICAL' AS SYS_PARAM_DESC,
    'Individual Life Medical Exam Document Storage Path' AS CODE_SUB_CODE_DESC
  FROM DUAL
) s
ON (t.SYS_PARAM_CODE = s.SYS_PARAM_CODE AND t.SYS_SUB_PARAM = s.SYS_SUB_PARAM)
WHEN NOT MATCHED THEN
  INSERT (SYS_PARAM_CODE, SYS_PARAM_DESC, SYS_SUB_PARAM, CODE_SUB_CODE_DESC, SYS_CREATED_AT, SYS_CREATED_BY)
  VALUES (s.SYS_PARAM_CODE, s.SYS_PARAM_DESC, s.SYS_SUB_PARAM, s.CODE_SUB_CODE_DESC, SYSDATE, 'ADMIN');

COMMIT;
