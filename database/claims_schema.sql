-- 1. Create Sequences safely
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_cnt FROM user_sequences WHERE sequence_name = 'SEQ_CLAIM_ID';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_CLAIM_ID START WITH 10001 INCREMENT BY 1 NOCACHE NOCYCLE';
  END IF;

