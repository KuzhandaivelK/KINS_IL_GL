-- 7. Seed User Groups (RIUSER, CLAIMUSER) in STBL_CODE & Default Users in MTBL_USER
MERGE INTO STBL_CODE t
USING (
  SELECT 'USR_GRP' AS CODE, 'RIUSER' AS CODE_SUB_CODE, 'Reinsurance User' AS CODE_SUB_CODE_DESC FROM DUAL
  UNION ALL
  SELECT 'USR_GRP', 'CLAIMUSER', 'Claims User' FROM DUAL
) s
ON (t.CODE = s.CODE AND t.CODE_SUB_CODE = s.CODE_SUB_CODE)
WHEN NOT MATCHED THEN
  INSERT (CODE, CODE_SUB_CODE, CODE_SUB_CODE_DESC)
  VALUES (s.CODE, s.CODE_SUB_CODE, s.CODE_SUB_CODE_DESC);

MERGE INTO MTBL_USER t
USING (
  SELECT 'riuser' AS USER_ID, 'Password@123' AS USER_PASSWORD, 'Reinsurance Officer' AS USER_NAME, 'Reinsurance Treaty & Cession User' AS USER_L1_DESC, 'RIUSER' AS USER_GROUP FROM DUAL
  UNION ALL
  SELECT 'claimuser', 'Password@123', 'Claims Officer', 'Claims Assessment & Settlement User', 'CLAIMUSER' FROM DUAL
) s
ON (LOWER(t.USER_ID) = LOWER(s.USER_ID))
WHEN NOT MATCHED THEN
  INSERT (USER_ID, USER_PASSWORD, USER_NAME, USER_L1_DESC, USER_DISABLE_FLAG, USER_LOGIN_COUNT, USER_CREATED_AT, USER_CREATED_BY, USER_GROUP)
  VALUES (s.USER_ID, s.USER_PASSWORD, s.USER_NAME, s.USER_L1_DESC, 'N', 0, SYSDATE, 'admin', s.USER_GROUP);

-- 8. Seed Treaty Setup Menu Item under Administration (MTBL_MENU)
