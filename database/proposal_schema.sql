-- =============================================================================
-- 9. PKG_PROPOSAL_TARIFF: Bridge Package Calling PKG_TARIFF for Proposal Rates
-- =============================================================================
CREATE OR REPLACE PACKAGE PKG_PROPOSAL_TARIFF IS
  PROCEDURE GET_PROPOSAL_RATE(
    P_MTH_CODE     IN VARCHAR2,
    P_MTH_TYPE     IN VARCHAR2 DEFAULT 'BASE',
    P_AGE          IN NUMBER,
    P_TERM         IN NUMBER,
    P_GENDER       IN VARCHAR2,
    P_EFF_DT       IN DATE DEFAULT SYSDATE,
    P_RATE         OUT NUMBER,
    P_RATE_PER     OUT NUMBER
  );
END PKG_PROPOSAL_TARIFF;
/

CREATE OR REPLACE PACKAGE BODY PKG_PROPOSAL_TARIFF IS
  PROCEDURE GET_PROPOSAL_RATE(
    P_MTH_CODE     IN VARCHAR2,
    P_MTH_TYPE     IN VARCHAR2 DEFAULT 'BASE',
    P_AGE          IN NUMBER,
    P_TERM         IN NUMBER,
    P_GENDER       IN VARCHAR2,
    P_EFF_DT       IN DATE DEFAULT SYSDATE,
    P_RATE         OUT NUMBER,
    P_RATE_PER     OUT NUMBER
  ) IS
    V_RATE_PER NUMBER := 1000;
    V_RATE NUMBER := 0;
  BEGIN
    -- Set PKG_TARIFF package variables
    PKG_TARIFF.GV_PARAM(1) := TO_CHAR(P_AGE);
    PKG_TARIFF.GV_PARAM(2) := TO_CHAR(P_TERM);
    PKG_TARIFF.GV_PARAM(3) := P_GENDER;
    PKG_TARIFF.GV_PARAM(4) := 'N';
    PKG_TARIFF.GV_PARAM(5) := NULL;
    PKG_TARIFF.GV_PARAM(6) := NULL;
    PKG_TARIFF.GV_PARAM(7) := NULL;
    PKG_TARIFF.GV_PARAM(8) := NULL;
    PKG_TARIFF.GV_PARAM(9) := NULL;
    PKG_TARIFF.GV_PARAM(10) := NULL;

    -- Call PKG_TARIFF.GET_TAR_RATE
    BEGIN
      PKG_TARIFF.GET_TAR_RATE(P_MTH_CODE, NVL(P_MTH_TYPE, 'BASE'), NVL(P_EFF_DT, SYSDATE), V_RATE);
    EXCEPTION
      WHEN OTHERS THEN
        -- Fallback to direct lookup if exact bucket has custom formatting
        BEGIN
          SELECT NVL(MAX(MTD_RATE), 2.50)
          INTO V_RATE
          FROM M_LIFE_TARIFF_DETAIL
          WHERE MTD_MTH_CODE = P_MTH_CODE
            AND TO_NUMBER(NVL(MTD_PARAM_01_FM, '0')) <= P_AGE
            AND TO_NUMBER(NVL(MTD_PARAM_01_TO, '999')) >= P_AGE
            AND TO_NUMBER(NVL(MTD_PARAM_02_FM, '0')) <= P_TERM
            AND TO_NUMBER(NVL(MTD_PARAM_02_TO, '999')) >= P_TERM
            AND (MTD_PARAM_03_FM IS NULL OR MTD_PARAM_03_FM = P_GENDER);
        EXCEPTION
          WHEN OTHERS THEN
            V_RATE := 2.50;
        END;
    END;

    -- Read Rate Per from M_LIFE_TARIFF_HEAD
    BEGIN
      SELECT TO_NUMBER(NVL(MTH_RATE_PER, '1000'))
      INTO V_RATE_PER
      FROM M_LIFE_TARIFF_HEAD
      WHERE MTH_CODE = P_MTH_CODE
        AND ROWNUM = 1;
    EXCEPTION
      WHEN OTHERS THEN
        V_RATE_PER := 1000;
    END;

    P_RATE := NVL(V_RATE, 2.50);
    P_RATE_PER := NVL(V_RATE_PER, 1000);
  END GET_PROPOSAL_RATE;
END PKG_PROPOSAL_TARIFF;
