-- =============================================================================
-- TABLE 1: T_PROPOSAL_INFO (Header / Plan Information)
-- =============================================================================
CREATE TABLE T_PROPOSAL_INFO (
  PROP_ID                   NUMBER            DEFAULT SEQ_PROP_ID.NEXTVAL NOT NULL,
  PROP_NO                   VARCHAR2(30)      NOT NULL,
  PROP_UID                  VARCHAR2(36)      NOT NULL,
  PROP_DATE                 DATE              DEFAULT SYSDATE NOT NULL,
  PROP_PROD_CODE            VARCHAR2(20)      NOT NULL,
  PROP_PLAN_TYPE            VARCHAR2(30)      DEFAULT 'TERM' NOT NULL,
  PROP_TERM                 NUMBER(3,0)       NOT NULL,
  PROP_PREM_PAY_TERM        NUMBER(3,0)       NOT NULL,
  PROP_SUM_ASSURED          NUMBER(17,3)      NOT NULL,
  PROP_PAY_FREQ             VARCHAR2(10)      DEFAULT 'ANNUAL' NOT NULL,
  PROP_STATUS               VARCHAR2(20)      DEFAULT 'DRAFT' NOT NULL,
  PROP_CURRENT_LEVEL        NUMBER(2,0)       DEFAULT 1 NOT NULL,
  PROP_ASSIGNED_ROLE        VARCHAR2(50)      DEFAULT 'MAKER' NOT NULL,
  PROP_UW_DECISION          VARCHAR2(30),
  PROP_UW_REMARKS           VARCHAR2(1000),
  IS_ACTIVE                 VARCHAR2(1)       DEFAULT 'Y' NOT NULL,
  CREATED_BY                VARCHAR2(26)      DEFAULT 'ADMIN' NOT NULL,
  CREATED_ON                DATE              DEFAULT SYSDATE NOT NULL,
  MODIFIED_BY               VARCHAR2(26),
  MODIFIED_ON               DATE,
  CONSTRAINT PK_PROP_INFO PRIMARY KEY (PROP_ID),
  CONSTRAINT UQ_PROP_NO UNIQUE (PROP_NO),
  CONSTRAINT UQ_PROP_UID UNIQUE (PROP_UID),
  CONSTRAINT CHK_PROP_STATUS CHECK (PROP_STATUS IN ('DRAFT', 'SUBMITTED', 'UNDERWRITING', 'APPROVED', 'REJECTED', 'REWORK', 'CONVERTED')),
  CONSTRAINT CHK_PROP_FREQ CHECK (PROP_PAY_FREQ IN ('ANNUAL', 'SEMI_ANNUAL', 'QUARTERLY', 'MONTHLY', 'SINGLE')),
  CONSTRAINT CHK_PROP_ACT CHECK (IS_ACTIVE IN ('Y', 'N'))
);

COMMENT ON TABLE T_PROPOSAL_INFO IS 'Core proposal header and plan details with UID and workflow level';

