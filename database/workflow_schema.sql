-- 3. Workflow Header Table
CREATE TABLE MTBL_WORKFLOW_HEAD (
  WF_CODE                   VARCHAR2(30)    NOT NULL,
  WF_NAME                   VARCHAR2(150)   NOT NULL,
  WF_CATEGORY               VARCHAR2(50)    NOT NULL,
  WF_DESC                   VARCHAR2(500),
  WF_TOTAL_LEVELS           NUMBER(2,0)     DEFAULT 1 NOT NULL,
  WF_ALLOW_AUTO_APPROVAL_YN VARCHAR2(1)     DEFAULT 'N' NOT NULL,
  WF_AUTO_APPROVAL_LIMIT    NUMBER(17,3)    DEFAULT 0,
  IS_ACTIVE                 VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
  CREATED_BY                VARCHAR2(26)    DEFAULT 'ADMIN' NOT NULL,
  CREATED_ON                DATE            DEFAULT SYSDATE NOT NULL,
  MODIFIED_BY               VARCHAR2(26),
  MODIFIED_ON               DATE,
  CONSTRAINT PK_WF_HEAD PRIMARY KEY (WF_CODE),
  CONSTRAINT CHK_WF_HEAD_ACT CHECK (IS_ACTIVE IN ('Y', 'N')),
  CONSTRAINT CHK_WF_HEAD_AUTO CHECK (WF_ALLOW_AUTO_APPROVAL_YN IN ('Y', 'N'))
);

COMMENT ON TABLE MTBL_WORKFLOW_HEAD IS 'Master table defining configurable business workflows for life insurance events';
COMMENT ON COLUMN MTBL_WORKFLOW_HEAD.WF_CODE IS 'Unique workflow process code (e.g. WF_PROP_CREATE, WF_UNDERWRITING)';
COMMENT ON COLUMN MTBL_WORKFLOW_HEAD.WF_NAME IS 'Descriptive name of the business process';
COMMENT ON COLUMN MTBL_WORKFLOW_HEAD.WF_CATEGORY IS 'Module category: NEW_BUSINESS, UNDERWRITING, POLICY_ADMIN, CLAIMS, FINANCE';

-- 4. Workflow Level / Approval Stage Table
CREATE TABLE MTBL_WORKFLOW_LEVEL (
  WFL_ID                    NUMBER          DEFAULT SEQ_WFL_ID.NEXTVAL NOT NULL,
  WF_CODE                   VARCHAR2(30)    NOT NULL,
  WFL_LEVEL_NO              NUMBER(2,0)     NOT NULL,
  WFL_LEVEL_NAME            VARCHAR2(100)   NOT NULL,
  WFL_ROLE_CODE             VARCHAR2(50)    NOT NULL,
  WFL_MIN_AMOUNT            NUMBER(17,3)    DEFAULT 0,
  WFL_MAX_AMOUNT            NUMBER(17,3),
  WFL_SLA_HOURS             NUMBER(4,0)     DEFAULT 24,
  WFL_ALLOW_REJECT_YN       VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
  WFL_ALLOW_REWORK_YN       VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
  WFL_MANDATORY_DOC_YN      VARCHAR2(1)     DEFAULT 'N' NOT NULL,
  WFL_AUTO_ESCALATE_HOURS   NUMBER(4,0)     DEFAULT 48,
  IS_ACTIVE                 VARCHAR2(1)     DEFAULT 'Y' NOT NULL,
  CREATED_BY                VARCHAR2(26)    DEFAULT 'ADMIN' NOT NULL,
  CREATED_ON                DATE            DEFAULT SYSDATE NOT NULL,
  MODIFIED_BY               VARCHAR2(26),
  MODIFIED_ON               DATE,
  CONSTRAINT PK_WF_LEVEL PRIMARY KEY (WFL_ID),
  CONSTRAINT FK_WF_LEVEL_HEAD FOREIGN KEY (WF_CODE) REFERENCES MTBL_WORKFLOW_HEAD(WF_CODE) ON DELETE CASCADE,
  CONSTRAINT UQ_WF_LEVEL_NO UNIQUE (WF_CODE, WFL_LEVEL_NO),
  CONSTRAINT CHK_WFL_ACT CHECK (IS_ACTIVE IN ('Y', 'N')),
  CONSTRAINT CHK_WFL_REJ CHECK (WFL_ALLOW_REJECT_YN IN ('Y', 'N')),
  CONSTRAINT CHK_WFL_REW CHECK (WFL_ALLOW_REWORK_YN IN ('Y', 'N')),
  CONSTRAINT CHK_WFL_DOC CHECK (WFL_MANDATORY_DOC_YN IN ('Y', 'N'))
);

COMMENT ON TABLE MTBL_WORKFLOW_LEVEL IS 'Configurable multi-level approval stages for each workflow process';

-- 5. Workflow Transaction Audit Log Table
CREATE TABLE TTBL_WORKFLOW_LOG (
  WFLOG_ID                  NUMBER          DEFAULT SEQ_WFLOG_ID.NEXTVAL NOT NULL,
  WF_CODE                   VARCHAR2(30)    NOT NULL,
  WFL_LEVEL_NO              NUMBER(2,0)     NOT NULL,
  REF_TRANS_NO              VARCHAR2(50)    NOT NULL,
  ACTION_TYPE               VARCHAR2(20)    NOT NULL,
  ACTION_BY                 VARCHAR2(26)    NOT NULL,
  ACTION_DATE               DATE            DEFAULT SYSDATE NOT NULL,
  COMMENTS                  VARCHAR2(1000),
  AMOUNT                    NUMBER(17,3),
  CONSTRAINT PK_WF_LOG PRIMARY KEY (WFLOG_ID)
);

